export function isSupabaseHost(connectionString: string): boolean {
  try {
    const host = new URL(connectionString).hostname;
    return host.endsWith(".supabase.com") || host.endsWith(".supabase.co");
  } catch {
    return false;
  }
}

/** TLS options for node-postgres, or undefined to keep the driver default (local database). */
export function sslFor(connectionString: string): { ca: string; rejectUnauthorized: true } | undefined {
  return isSupabaseHost(connectionString) ? { ca: SUPABASE_ROOT_CA, rejectUnauthorized: true } : undefined;
}
